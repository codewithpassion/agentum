// Builds the sandbox helper (`src/transfer-main.ts` and what it imports) into one
// script and writes it, as a string, to `src/transfer-bundle.generated.ts`. The
// Worker cannot read files at run time, so the managed runtime ships the
// helper as this constant. Run `bun run bundle` after changing a `transfer*.ts`
// source. A test fails when the committed file no longer matches the sources.
import { build, write } from "bun";
import { transferSourceHash } from "./transfer-sources.ts";

const OUT = new URL("../src/transfer-bundle.generated.ts", import.meta.url);

const built = await build({
  entrypoints: [new URL("../src/transfer-main.ts", import.meta.url).pathname],
  minify: true,
  target: "bun",
});
const [output] = built.outputs;
if (!(built.success && output)) {
  throw new Error(
    `Bundling the transfer helper failed: ${built.logs.join("\n")}`
  );
}
const source = await output.text();

await write(
  OUT,
  `// Generated by \`bun run bundle\` in packages/library-sync. Do not edit.
export const TRANSFER_SOURCE_HASH = ${JSON.stringify(await transferSourceHash())};

export const TRANSFER_HELPER_SOURCE = ${JSON.stringify(source)};
`
);
console.log(`wrote ${OUT.pathname} (${source.length} bytes of script)`);
